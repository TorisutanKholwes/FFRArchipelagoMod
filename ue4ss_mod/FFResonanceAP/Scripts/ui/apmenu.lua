--[[
  "Archipelago Options" button and panel on the title screen (TD-032).

  The title menu (WBP_TitleLayout_C > WBP_DirectionLayoutMenu > DirectionGridPanel > WBP_Title_ListEntry_C)
  is generated by game Blueprints, so a separate button is added to the title layout's own widget tree
  instead of a 6th entry: it is shown and destroyed together with the title menu.
  Widgets are plain UMG classes built with StaticConstructObject. Text uses the font of a title menu
  entry, because the game ships no Slate font files (Engine/Content/Slate has only Cursor/).

  Clicks: each button's OnClicked delegate is bound to the button's own UWidget:ForceLayoutPrepass
  (no parameters, harmless), and that UFunction is hooked; IsPressed polling is the fallback.
  Keyboard: the title menu is driven by the game's EnhancedUI layer from Enhanced Input actions, which
  receive every key a text box does not consume (Z/S moved the menu while typing, 2026-11-09). While the
  panel is open, a mapping context of our own with the highest priority maps every keyboard/gamepad key
  to a dummy action that consumes input, so the game's lower-priority contexts never see them; typed
  characters still reach the text box (Slate handles them before Enhanced Input). Closing the panel
  removes that context; nothing of the game's own input setup is changed.

  Settings logic (validation, connection.json, connect_request.json, status text): ap/connconfig.lua.
]]

