--- A text widget of a title menu entry, used as the font source for our texts.
local function font_source()
    -- Prefer a live entry (under /Engine/Transient) over the class template's text block.
    local template, template_text
    for _, cls in ipairs({ "CommonTextBlock", "TextBlock" }) do
        for _, t in ipairs(safe(function() return FindAllOf(cls) end) or {}) do
            local fn = safe(function() return t:GetFullName() end) or ""
            if fn:find("WBP_Title_ListEntry_C", 1, true) and not fn:find("Default__", 1, true) then
                local text = safe(function() return t:GetText():ToString() end)
                if text and text ~= "" then
                    if fn:find("/Engine/Transient", 1, true) then return t, text end
                    template, template_text = template or t, template_text or text
                end
            end
        end
    end
    return template, template_text
end

-- Widget builders ---------------------------------------------------------

local function make_text(outer, text, size, color)
    return W.make_text(outer, text, size, color or COLORS.white, apmenu.font_src)
end

local function make_button(outer, label, size, action)
    local b = construct(C.Button, outer)
    try(b, "SetBackgroundColor", COLORS.button)
    local text = make_text(outer, label, size)
    try(b, "SetContent", text)
    local ok, err = pcall(function() b.OnClicked:Add(b, "ForceLayoutPrepass") end)
    if not ok then log.warn("UI: binding OnClicked for '%s' failed (polling only): %s", label, tostring(err)) end
    local a = addr(b)
    if a then apmenu.targets[a] = action end
    apmenu.poll[action] = { was_pressed = false, hook_tick = -100 }
    return b, text
end

local function sized(outer, child, width)
    local box = construct(C.SizeBox, outer)
    try(box, "SetWidthOverride", width)
    try(box, "SetContent", child)
    return box
end

local function make_field(outer, hint, is_password)
    local box = construct(C.EditableTextBox, outer)
    if apmenu.font_src and valid(apmenu.font_src) then
        local ok, err = pcall(function() box.WidgetStyle.TextStyle.Font = apmenu.font_src.Font end)
        if not ok then log.warn("UI: text box font not set: %s", tostring(err)) end
        pcall(function() box.WidgetStyle.TextStyle.Font.Size = 22 end)
    end
    pcall(function() box.WidgetStyle.ForegroundColor = slate_color(COLORS.black) end)
    try(box, "SetForegroundColor", COLORS.black)
    try(box, "SetHintText", FText(hint))
    pcall(function() box.ClearKeyboardFocusOnCommit = false end)
    pcall(function() box.SelectAllTextWhenFocused = true end)
    if is_password then try(box, "SetIsPassword", true) end
    -- Our own light frame: readable even if the engine's default text box images are not shipped.
    local frame = construct(C.Border, outer)
    try(frame, "SetBrushColor", COLORS.field)
    try(frame, "SetPadding", { Left = 8, Top = 4, Right = 8, Bottom = 4 })
    try(frame, "SetContent", box)
    return box, frame
end

local function add_row(vbox, widget, top, halign)
    local slot = safe(function() return vbox:AddChildToVerticalBox(widget) end)
    if slot then
        pcall(function() slot:SetPadding({ Left = 0, Top = top or 6, Right = 0, Bottom = 0 }) end)
        if halign then pcall(function() slot:SetHorizontalAlignment(halign) end) end
    else
        log.warn("UI: AddChildToVerticalBox failed for %s", name_of(widget))
    end
    return slot
end

local function add_cell(hbox, widget, left)
    local slot = safe(function() return hbox:AddChildToHorizontalBox(widget) end)
    if slot then
        pcall(function() slot:SetPadding({ Left = left or 0, Top = 0, Right = 0, Bottom = 0 }) end)
        pcall(function() slot:SetVerticalAlignment(VALIGN.Center) end)
    end
    return slot
end

local function field_row(outer, vbox, label, hint, value, is_password)
    local row = construct(C.HorizontalBox, outer)
    add_cell(row, sized(outer, make_text(outer, label, 22), 200))
    local box, frame = make_field(outer, hint, is_password)
    add_cell(row, sized(outer, frame, 560), 12)
    if value and value ~= "" then try(box, "SetText", FText(value)) end
    add_row(vbox, row, 10)
    return box
end

--- Place `widget` in `parent` (canvas, overlay or other panel). Returns true on success.
local function place(parent, widget, where, z)
    local pcls = cls_name(parent)
    if pcls:find("CanvasPanel", 1, true) then
        local slot = parent:AddChildToCanvas(widget)
        if not slot then return false end
        if where == "corner" then
            slot:SetAnchors({ Minimum = { X = 1, Y = 0 }, Maximum = { X = 1, Y = 0 } })
            slot:SetAlignment({ X = 1, Y = 0 })
            slot:SetPosition({ X = -60, Y = 60 })
        else
            slot:SetAnchors({ Minimum = { X = 0.5, Y = 0.5 }, Maximum = { X = 0.5, Y = 0.5 } })
            slot:SetAlignment({ X = 0.5, Y = 0.5 })
            slot:SetPosition({ X = 0, Y = 0 })
        end
        slot:SetAutoSize(true)
        slot:SetZOrder(z)
        return true
    end
    local slot
    if pcls:find("Overlay", 1, true) then
        slot = parent:AddChildToOverlay(widget)
    else
        slot = parent:AddChild(widget)
    end
    if not slot then return false end
    pcall(function()
        if where == "corner" then
            slot:SetHorizontalAlignment(HALIGN.Right)
            slot:SetVerticalAlignment(VALIGN.Top)
            slot:SetPadding({ Left = 0, Top = 60, Right = 60, Bottom = 0 })
        else
            slot:SetHorizontalAlignment(HALIGN.Center)
            slot:SetVerticalAlignment(VALIGN.Center)
        end
    end)
    return true
end

-- Connection status under the button ---------------------------------------

--- Green "Connected as <slot>" or red "Disconnected" (connconfig.connection_label); the widget is
--- only touched when the text changes.
refresh_connection_label = function()
    local w = apmenu.w
    if not valid(w.conn) then return end
    local st = ipc.read_bridge_state()
    local text, kind = connconfig.connection_label(st, os.time(), apmenu.runtime and apmenu.runtime.armed_seq)
    if text == apmenu.conn_label then return end
    apmenu.conn_label = text
    try(w.conn, "SetText", FText(text))
    try(w.conn, "SetColorAndOpacity", slate_color(COLORS[kind] or COLORS.error))
    log.info("UI: title status: %s", text)
end

-- Injection ---------------------------------------------------------------

local function build(layout)
    local tree = layout.WidgetTree
    if not valid(tree) then error("title layout has no WidgetTree") end
    local root = tree.RootWidget
    if not valid(root) then error("title layout has no root widget") end
    local parent, outer = root, tree
    apmenu.fallback_parent = false
    if safe(function() return root:GetChildrenCount() end) == nil then
        -- Root is not a panel: use the persistent game layout's overlay (removed when leaving the title).
        local overall = FindFirstOf("WBP_OverAllLayout_C")
        local ov = valid(overall) and find_widget(overall.WidgetTree.RootWidget, "Overlay_0") or nil
        if not valid(ov) then error("no panel to attach to (title root " .. cls_name(root) .. ")") end
        parent, outer = ov, overall.WidgetTree
        apmenu.fallback_parent = true
    end
    log.info("UI: title layout %s, root %s [%s], attaching to %s [%s]", name_of(layout), name_of(root), cls_name(root),
        name_of(parent), cls_name(parent))

    local src, src_text = font_source()
    apmenu.font_src = src
    log.info("UI: font source %s (text %q)", src and safe(function() return src:GetFullName() end) or "none", tostring(src_text))

    apmenu.targets, apmenu.poll, apmenu.w = {}, {}, {}
    local w = apmenu.w

    -- The button.
    -- The button, with the connection status ("Connected as <slot>" / "Disconnected") below it.
    w.corner = construct(C.VerticalBox, outer)
    w.button = make_button(outer, BUTTON_LABEL, 26, "open")
    try(w.button, "SetToolTipText", FText("Server, port and slot for Archipelago"))
    add_row(w.corner, w.button, 0, HALIGN.Fill)
    w.conn = make_text(outer, "Disconnected", 22, COLORS.error)
    add_row(w.corner, w.conn, 6, HALIGN.Center)
    if not place(parent, w.corner, "corner", 100) then error("could not place the button") end
    apmenu.conn_label = nil
    refresh_connection_label()

    -- The panel (hidden until opened).
    local cfg, why = connconfig.load(apmenu.config_path)
    if why == "unreadable" then log.warn("UI: config/connection.json unreadable, using defaults") end
    w.panel = construct(C.Border, outer)
    try(w.panel, "SetBrushColor", COLORS.panel)
    try(w.panel, "SetPadding", { Left = 36, Top = 28, Right = 36, Bottom = 28 })
    local vbox = construct(C.VerticalBox, outer)
    try(w.panel, "SetContent", vbox)
    add_row(vbox, make_text(outer, "Archipelago Options", 32), 0, HALIGN.Center)
    w.server = field_row(outer, vbox, "Server", "archipelago.gg or localhost", cfg.server, false)
    w.port = field_row(outer, vbox, "Port", "38281", tostring(cfg.port), false)
    w.slot = field_row(outer, vbox, "Slot name", "the name in your YAML", cfg.slot, false)
    w.password = field_row(outer, vbox, "Password", "leave empty if the room has none", "", true)
    w.status = make_text(outer, "", 20, COLORS.idle)
    pcall(function() w.status:SetAutoWrapText(true) end)
    add_row(vbox, sized(outer, w.status, 772), 18)
    local buttons = construct(C.HorizontalBox, outer)
    w.connect = make_button(outer, "Connect", 24, "connect")
    w.back = make_button(outer, "Back", 24, "back")
    add_cell(buttons, sized(outer, w.connect, 220))
    add_cell(buttons, sized(outer, w.back, 220), 24)
    add_row(vbox, buttons, 22, HALIGN.Center)
    try(w.panel, "SetVisibility", VIS.Collapsed)
    if not place(parent, w.panel, "center", 200) then error("could not place the panel") end
    w.parent = parent
end

local function remove_widgets()
    for _, k in ipairs({ "corner", "panel" }) do
        local x = apmenu.w[k]
        if valid(x) then pcall(function() x:RemoveFromParent() end) end
    end
    apmenu.w, apmenu.targets, apmenu.poll = {}, {}, {}
end

local function ensure_button()
    -- Fast path: the layout we injected into still exists with our button.
    if valid(apmenu.layout) and valid(apmenu.w.button) and addr(apmenu.layout) == apmenu.layout_addr then return end
    -- FindFirstOf walks the whole object array: at most once per second.
    if apmenu.ticks < apmenu.next_search then return end
    apmenu.next_search = apmenu.ticks + 10
    local layout = FindFirstOf("WBP_TitleLayout_C")
    if not valid(layout) then return end
    local a = addr(layout)
    if a == apmenu.layout_addr and valid(apmenu.w.button) then
        apmenu.layout = layout
        return
    end
    if a == apmenu.failed_layout_addr then return end
    if apmenu.fallback_parent then remove_widgets() end
    apmenu.panel_open = false
    local ok, err = pcall(build, layout)
    if ok then
        apmenu.layout_addr = a
        apmenu.layout = layout
        log.info("UI: '%s' button added to the title screen", BUTTON_LABEL)
    else
        apmenu.failed_layout_addr = a  -- do not retry every tick on the same layout
        log.error("UI: could not add the '%s' button: %s", BUTTON_LABEL, tostring(err))
        pcall(remove_widgets)
    end
end

-- Title menu input --------------------------------------------------------

--- Call an IEnhancedInputSubsystemInterface function on the local player subsystem: directly, or
--- through the interface's UFunction with the subsystem as context.
local function call_input_subsystem(sub, fname, ...)
    local args = table.pack(...)
    local ok, err = pcall(function() return sub[fname](sub, table.unpack(args, 1, args.n)) end)
    if ok then return true end
    local fn = StaticFindObject(IFACE .. fname)
    if not valid(fn) then return false, "direct call: " .. tostring(err) .. "; interface function not found" end
    local ok2, err2 = pcall(function() return fn(sub, table.unpack(args, 1, args.n)) end)
    if ok2 then return true end
    return false, "direct call: " .. tostring(err) .. "; interface call: " .. tostring(err2)
end

local CONTEXT_OPTIONS = { bIgnoreAllPressedKeysUntilRelease = false, bForceImmediately = true, bNotifyUserSettings = false }

local function block_game_keys()
    if apmenu.block then return true end
    local sub = FindFirstOf("EnhancedInputLocalPlayerSubsystem")
    if not valid(sub) then
        log.error("UI: EnhancedInputLocalPlayerSubsystem not found; keys are NOT blocked")
        return false
    end
    local outer = StaticFindObject("/Engine/Transient")
    local action = construct("/Script/EnhancedInput.InputAction", outer)
    pcall(function() action.bConsumeInput = true end)
    local imc = construct("/Script/EnhancedInput.InputMappingContext", outer)
    pcall(function() imc.InputModeFilterOptions = 2 end)  -- DoNotFilter: active in UI and game input modes
    local mapped, failed = 0, 0
    for _, key in ipairs(BLOCKED_KEYS) do
        if pcall(function() imc:MapKey(action, { KeyName = FName(key) }) end) then mapped = mapped + 1 else failed = failed + 1 end
    end
    local ok, err = call_input_subsystem(sub, "AddMappingContext", imc, BLOCK_PRIORITY, CONTEXT_OPTIONS)
    if not ok then
        log.error("UI: could not add the key-blocking mapping context (keys are NOT blocked): %s", tostring(err))
        return false
    end
    apmenu.block = { sub = sub, imc = imc, action = action }
    log.info("UI: game keys blocked while the panel is open (%d keys mapped, %d failed)", mapped, failed)
    return true
end

local function unblock_game_keys()
    local b = apmenu.block
    if not b then return end
    apmenu.block = nil
    if not (valid(b.sub) and valid(b.imc)) then
        log.warn("UI: key-blocking context already gone")
        return
    end
    local ok, err = call_input_subsystem(b.sub, "RemoveMappingContext", b.imc, CONTEXT_OPTIONS)
    if ok then
        log.info("UI: game keys restored")
    else
        log.error("UI: could not remove the key-blocking mapping context: %s", tostring(err))
    end
end

--- Diagnostic: log when the title menu still receives navigation while the panel is open.
local function hook_menu_navigation()
    if apmenu.nav_hooked then return end
    local menu = FindFirstOf("WBP_DirectionLayoutMenu_C")
    local cls = valid(menu) and safe(function() return menu:GetClass():GetFullName() end)
    local path = cls and cls:match("^%S+%s+(.+)$")
    if not path then return end
    apmenu.nav_hooked = true
    local ok, err = pcall(RegisterHook, path .. ":InputDirection", function(_, nav)
        if apmenu.panel_open then
            log.warn("UI: title menu received navigation %s while the panel is open",
                tostring(safe(function() return nav:get() end)))
        end
    end)
    log.info("UI: menu navigation diagnostic hook %s (%s)", ok and "registered" or "failed", ok and path or tostring(err))
end

local function set_title_input(enabled)
    local layout = valid(apmenu.layout) and apmenu.layout or FindFirstOf("WBP_TitleLayout_C")
    local menu = valid(layout) and find_widget(layout.WidgetTree.RootWidget, "WBP_DirectionLayoutMenu") or nil
    if valid(menu) then
        try(menu, "SetIsEnabled", enabled)
    else
        log.warn("UI: title menu widget not found (input %s)", enabled and "on" or "off")
    end
    local ctrl = FindFirstOf("CPP_TitleController")
    local pc = FindFirstOf("PlayerController")
    if valid(ctrl) and valid(pc) then
        try(ctrl, enabled and "EnableInput" or "DisableInput", pc)
    else
        log.warn("UI: title controller or player controller not found (input %s)", enabled and "on" or "off")
    end
end

-- Panel actions -----------------------------------------------------------

local function field_text(box)
    return safe(function() return box:GetText():ToString() end) or ""
end

local function show_status(text, kind)
    local w = apmenu.w
    if not valid(w.status) then return end
    try(w.status, "SetText", FText(text))
    try(w.status, "SetColorAndOpacity", slate_color(COLORS[kind] or COLORS.idle))
end

local function refresh_status()
    if apmenu.status_override then
        show_status(apmenu.status_override.text, apmenu.status_override.kind)
        return
    end
    local st, problem = ipc.read_bridge_state()
    local text, kind = connconfig.describe_status(st, problem, os.time(), apmenu.last_seq)
    if apmenu.last_seq == nil and kind ~= "error" then
        text = text .. " - enter the settings and press Connect"
    end
    show_status(text, kind)
end

local function open_panel()
    local w = apmenu.w
    if not valid(w.panel) then return end
    apmenu.status_override = nil
    apmenu.title_input_warned = false
    pcall(hook_menu_navigation)
    local bok, berr = pcall(block_game_keys)
    if not bok then log.error("UI: blocking game keys failed: %s", tostring(berr)) end
    set_title_input(false)
    try(w.panel, "SetVisibility", VIS.Visible)
    try(w.corner, "SetVisibility", VIS.Collapsed)
    apmenu.panel_open = true
    refresh_status()
    try(w.server, "SetKeyboardFocus")
    log.info("UI: Archipelago Options opened")
end

local function close_panel()
    local w = apmenu.w
    if valid(w.panel) then try(w.panel, "SetVisibility", VIS.Collapsed) end
    if valid(w.corner) then try(w.corner, "SetVisibility", VIS.Visible) end
    if apmenu.panel_open then set_title_input(true) end
    local uok, uerr = pcall(unblock_game_keys)
    if not uok then log.error("UI: restoring game keys failed: %s", tostring(uerr)) end
    apmenu.panel_open = false
    apmenu.suppress_open_until = apmenu.ticks + 5  -- the click on Back must not reopen the panel
    apmenu.next_status = 0                         -- update the status under the button now
    log.info("UI: Archipelago Options closed")
end

local function connect()
    local w = apmenu.w
    local fields = { server = field_text(w.server), port = field_text(w.port), slot = field_text(w.slot) }
    local cfg, errors = connconfig.validate(fields)
    if not cfg then
        apmenu.status_override = { text = table.concat(errors, "\n"), kind = "error" }
        refresh_status()
        log.info("UI: Connect refused by validation: %s", table.concat(errors, "; "))
        return
    end
    apmenu.status_override = nil
    local sok, serr = connconfig.save(apmenu.config_path, cfg)
    if not sok then log.error("UI: cannot save config/connection.json: %s", tostring(serr)) end
    local password = field_text(w.password)
    local seq = connconfig.next_seq(apmenu.last_seq)
    local wok, werr = connconfig.write_request(apmenu.ipc_dir,
        connconfig.build_request(cfg, password, seq, apmenu.runtime.game_session))
    if not wok then
        apmenu.status_override = { text = "Cannot write the request for the bridge: " .. tostring(werr), kind = "error" }
        refresh_status()
        log.error("UI: cannot write connect_request.json: %s", tostring(werr))
        return
    end
    apmenu.last_seq = seq
    apmenu.runtime.arm(seq)
    log.info("UI: Connect -> %s, slot %s, password %s (request %d)", connconfig.address(cfg), cfg.slot,
        password ~= "" and "set" or "none", seq)
    refresh_status()
end

local ACTIONS = { open = open_panel, back = close_panel, connect = connect }

local function run_action(name, via)
    if name == "open" and (apmenu.panel_open or apmenu.ticks < (apmenu.suppress_open_until or 0)) then
        log.info("UI: '%s' click ignored (%s; panel just closed or already open)", name, via)
        return
    end
    if name ~= "open" and not apmenu.panel_open then
        log.info("UI: '%s' click ignored (%s; panel closed)", name, via)
        return
    end
    log.info("UI: '%s' clicked (%s)", name, via)
    local ok, err = pcall(ACTIONS[name])
    if not ok then log.error("UI: action '%s' failed: %s", name, tostring(err)) end
end

-- Click detection ---------------------------------------------------------

local function on_click_hook(ctx)
    local obj = safe(function() return ctx:get() end)
    local a = obj and addr(obj)
    local action = a and apmenu.targets[a]
    if action then
        apmenu.pending[#apmenu.pending + 1] = action
        if apmenu.poll[action] then apmenu.poll[action].hook_tick = apmenu.ticks end
    end
end

local function poll_buttons()
    local w = apmenu.w
    local buttons = { open = w.button, connect = w.connect, back = w.back }
    for action, b in pairs(buttons) do
        local p = apmenu.poll[action]
        if p and valid(b) then
            local pressed = safe(function() return b:IsPressed() end) == true
            if p.was_pressed and not pressed then
                -- Released: a click, unless the delegate hook already reported it.
                local hovered = safe(function() return b:IsHovered() end) == true
                if hovered and apmenu.ticks - p.hook_tick > 10 then
                    apmenu.pending[#apmenu.pending + 1] = action
                    p.poll_click = true
                end
            end
            p.was_pressed = pressed
        end
    end
end

-- Public ------------------------------------------------------------------

function apmenu.init(mod_dir, runtime)
    apmenu.mod_dir = mod_dir
    apmenu.runtime = runtime
    apmenu.config_path = fs.join(mod_dir, "config", "connection.json")
    apmenu.ipc_dir = fs.join(mod_dir, "ipc")
end

function apmenu.register_hooks()
    local ok, err = pcall(RegisterHook, "/Script/UMG.Widget:ForceLayoutPrepass", on_click_hook)
    log.info("UI: click hook %s%s", ok and "registered" or "NOT registered: ", ok and "" or tostring(err))
    for _, fn in ipairs({ "/Script/mucha.CPP_TitleController:InputMenu", "/Script/mucha.CPP_VM_Title:ExecuteEntry" }) do
        pcall(RegisterHook, fn, function()
            if apmenu.panel_open and not apmenu.title_input_warned then
                apmenu.title_input_warned = true
                log.warn("UI: title menu input reached the game while the panel is open (%s)", fn)
            end
        end)
    end
end

function apmenu.on_game_state(full_name)
    local was = apmenu.on_title
    apmenu.on_title = tostring(full_name):find("/Map/Title/", 1, true) ~= nil
    if was and not apmenu.on_title then
        if apmenu.panel_open then pcall(set_title_input, true) end
        pcall(unblock_game_keys)
        if apmenu.fallback_parent then pcall(remove_widgets) end
        apmenu.panel_open = false
        apmenu.w, apmenu.targets, apmenu.poll = {}, {}, {}
        apmenu.layout_addr, apmenu.failed_layout_addr, apmenu.layout = nil, nil, nil
    end
end

--- Game-thread tick (100 ms).
function apmenu.tick()
    apmenu.ticks = apmenu.ticks + 1
    if not apmenu.on_title then return end
    ensure_button()
    if not valid(apmenu.w.button) then return end
    poll_buttons()
    local actions = apmenu.pending
    apmenu.pending = {}
    local done = {}
    for _, a in ipairs(actions) do
        if not done[a] then
            done[a] = true
            run_action(a, apmenu.poll[a] and apmenu.poll[a].poll_click and "poll" or "delegate")
            if apmenu.poll[a] then apmenu.poll[a].poll_click = false end
        end
    end
    if apmenu.ticks >= apmenu.next_status then
        apmenu.next_status = apmenu.ticks + 10
        if apmenu.panel_open then refresh_status() else refresh_connection_label() end
    end
end

function apmenu.start()
    LoopInGameThreadWithDelay(100, function()
        local ok, err = pcall(apmenu.tick)
        if not ok then log.error("UI tick error: %s", tostring(err)) end
    end)
end

return apmenu
